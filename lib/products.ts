export const productCatalogHref = "/produkciya";

export type CatalogProduct = Product & {
  sectionId: string;
  sectionTitle: string;
  sectionKicker: string;
};

export function productHref(id: string) {
  return `${productCatalogHref}/${id}`;
}

export function allProducts(): CatalogProduct[] {
  return productSections.flatMap((section) =>
    section.products.map((product) => ({
      ...product,
      sectionId: section.id,
      sectionTitle: section.title,
      sectionKicker: section.kicker,
    })),
  );
}

export function getProductBySlug(slug: string): CatalogProduct | undefined {
  return allProducts().find((product) => product.id === slug);
}
